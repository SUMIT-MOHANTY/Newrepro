"""ToolRegistry — defines all tools as Anthropic-compatible tool definitions.

Converts the existing MCP tools into Claude's native tool-use format so that
Claude can call read_file, write_file, grep_search, find_and_replace, etc.
directly — just like how Claude works on claude.ai.

Each tool definition follows the Anthropic tool-use schema:
  { "name": "...", "description": "...", "input_schema": { JSON Schema } }
"""
from __future__ import annotations

from enum import Enum
from typing import Any


class ToolPhase(str, Enum):
    """Which phase of the agent lifecycle is running — controls which tools are available."""
    planning = "planning"
    followup_planning = "followup_planning"
    analysis = "analysis"
    coding = "coding"
    batch_coding = "batch_coding"
    editing = "editing"
    reviewing = "reviewing"
    build_fix = "build_fix"
    full = "full"  # All tools available



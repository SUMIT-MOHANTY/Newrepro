class ToolRegistry:
    """Central registry of all tools available to Claude's native tool-use API.

    Provides tool definitions in Anthropic format and maps tool names back
    to the corresponding MCP module + method for execution.
    """

    def __init__(
        self,
        *,
        web_search_enabled: bool = False,
        github_enabled: bool = False,
        dynamic_tools: list[dict[str, Any]] | None = None,
    ) -> None:
        import os
        self._web_search_enabled = web_search_enabled or os.environ.get("WEB_SEARCH_ENABLED", "").lower() == "true"
        self._github_enabled = github_enabled or bool(os.environ.get("GITHUB_TOKEN"))
        self._dynamic_tools: list[dict[str, Any]] = []

        # Process dynamic tools from external MCP servers
        if dynamic_tools:
            for tool in dynamic_tools:
                tool_name = tool.get("name", "")
                module_name = tool.get("_mcp_module", "custom_mcp")
                if not tool_name or module_name == "mcp_github" or "github" in tool_name.lower():
                    continue

                # Build Anthropic tool-use schema
                schema = tool.get("inputSchema") or {"type": "object", "properties": {}}
                if not isinstance(schema, dict):
                    schema = {"type": "object", "properties": {}}

                anthropic_tool = {
                    "name": tool_name,
                    "description": tool.get("description") or f"Tool from {module_name}",
                    "input_schema": schema,
                }
                self._dynamic_tools.append(anthropic_tool)

                # Register in mapping
                _TOOL_TO_MCP_MAP[tool_name] = (module_name, tool_name)
                print(f"[ToolRegistry] Registered dynamic tool: {tool_name} -> {module_name}.{tool_name}")

    def get_tools(self, phase: ToolPhase = ToolPhase.full) -> list[dict[str, Any]]:
        """Return tool definitions for the given agent phase."""
        if phase == ToolPhase.planning:
            return self._planning_tools()
        elif phase == ToolPhase.followup_planning:
            return self._followup_planning_tools()
        elif phase == ToolPhase.analysis:
            return self._analysis_tools()
        elif phase == ToolPhase.batch_coding:
            return self._batch_coding_tools()
        elif phase == ToolPhase.editing:
            return self._editing_tools()
        elif phase == ToolPhase.coding:
            return self._coding_tools()
        elif phase == ToolPhase.reviewing:
            return self._reviewing_tools()
        elif phase == ToolPhase.build_fix:
            return self._build_fix_tools()
        elif phase == ToolPhase.migration:
            return self._migration_tools()
        elif phase == ToolPhase.testing:
            return self._testing_tools()
        else:
            return self._all_tools()

    def get_mcp_mapping(self, tool_name: str) -> tuple[str, str] | None:
        """Return (mcp_module, mcp_method) for a tool name, or None if unknown."""
        return _TOOL_TO_MCP_MAP.get(tool_name)


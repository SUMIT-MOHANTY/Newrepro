"""
TokenOps — Pay-As-You-Go models.

Tables:
    payg_request — Approval workflow for enabling PAYG on an organization.
    payg_invoice — Monthly billing record for PAYG consumption.

Design rules:
    • Status transitions for PAYGRequest follow a linear state machine:
          REQUESTED → APPROVED | REJECTED
          APPROVED  → SUSPENDED
      Suspended orgs may re-request via a new PAYGRequest row.
    • Status is stored as a plain String (SQLite has no native ENUM type).
      A Python Enum is provided for application-level validation and type safety.
    • billing_month is stored as "YYYY-MM" string for O(1) lookup without date
      arithmetic at query time.
    • One invoice row per (organization_name, billing_month) pair — enforced by
      UniqueConstraint.
"""

import enum
from datetime import datetime
from decimal import Decimal

from sqlalchemy import (
    BigInteger,
    Boolean,
    Column,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    Numeric,
    String,
    Text,
    UniqueConstraint,
)
from sqlalchemy.orm import relationship

from database import Base


# ---------------------------------------------------------------------------
# Enums
# ---------------------------------------------------------------------------

class PAYGStatus(str, enum.Enum):
    """
    Lifecycle states for a PAYG enablement request.

    REQUESTED  — Initial state; awaiting Super Admin review.
    APPROVED   — Super Admin has enabled PAYG for the org.
    REJECTED   — Super Admin denied the request.
    SUSPENDED  — Previously approved; PAYG has been disabled.
    """
    REQUESTED  = "REQUESTED"
    APPROVED   = "APPROVED"
    REJECTED   = "REJECTED"
    SUSPENDED  = "SUSPENDED"


class InvoiceStatus(str, enum.Enum):
    """
    Billing states for a PAYG monthly invoice.

    PENDING  — Generated but not yet settled.
    PAID     — Payment confirmed.
    OVERDUE  — Past due date without payment.
    WAIVED   — Manually waived by Super Admin.
    """
    PENDING  = "PENDING"
    PAID     = "PAID"
    OVERDUE  = "OVERDUE"
    WAIVED   = "WAIVED"


# ---------------------------------------------------------------------------
# 5. PAYGRequest
# ---------------------------------------------------------------------------

class PAYGRequest(Base):
    """
    Pay-As-You-Go enablement request submitted by an Org Admin.

    Workflow:
        Org Admin submits request
            → Super Admin approves / rejects
                → On APPROVED: OrganizationWallet.payg_enabled = True
                → On REJECTED: No wallet change
                → On SUSPEND:  OrganizationWallet.payg_enabled = False

    Multiple historical requests per org are allowed (no unique constraint on
    organization_name) to maintain the full approval audit trail.
    """

    __tablename__ = "payg_request"
    __table_args__ = (
        Index("ix_payg_request_org_status", "organization_name", "status"),
    )

    id                = Column(Integer, primary_key=True, index=True)
    organization_name = Column(String, nullable=False, index=True)

    requested_by = Column(
        Integer, ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True, index=True,
        comment="Org Admin who submitted this request",
    )
    status = Column(
        String,
        nullable=False,
        default=PAYGStatus.REQUESTED.value,
        index=True,
        comment="One of: REQUESTED, APPROVED, REJECTED, SUSPENDED",
    )
    approved_by = Column(
        Integer, ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True,
        comment="Super Admin who actioned this request",
    )
    approved_at = Column(DateTime, nullable=True,
                         comment="Timestamp of approval or rejection")
    remarks     = Column(Text, nullable=True,
                         comment="Super Admin notes or rejection reason")
    created_at  = Column(DateTime, nullable=False, default=datetime.utcnow)

    requester = relationship("User", foreign_keys=[requested_by], lazy="select")
    approver  = relationship("User", foreign_keys=[approved_by],  lazy="select")

    @property
    def payg_status(self) -> PAYGStatus:
        """Return typed enum value for the current status."""
        return PAYGStatus(self.status)

    def __repr__(self) -> str:
        return (
            f"<PAYGRequest id={self.id} "
            f"org={self.organization_name!r} status={self.status!r}>"
        )


# ---------------------------------------------------------------------------
# 6. PAYGInvoice
# ---------------------------------------------------------------------------

class PAYGInvoice(Base):
    """
    Monthly PAYG billing record.

    One row per (organization_name, billing_month).
    Generated by the monthly billing job after rollup data is finalized.

    billing_month is stored as "YYYY-MM" for deterministic string comparison
    without date-range queries.

    total_cost uses Numeric(20, 8) for financial precision.
    """

    __tablename__ = "payg_invoice"
    __table_args__ = (
        UniqueConstraint(
            "organization_name", "billing_month",
            name="uq_payg_invoice_org_month",
        ),
        Index("ix_payg_invoice_org_month",    "organization_name", "billing_month"),
        Index("ix_payg_invoice_status",       "invoice_status"),
    )

    id                = Column(Integer, primary_key=True, index=True)
    organization_name = Column(String, nullable=False, index=True)
    organization_id   = Column(String(36), nullable=True, index=True)
    billing_month     = Column(String(7), nullable=False, index=True,
                               comment="Format: YYYY-MM, e.g. '2026-08'")
    total_tokens      = Column(BigInteger, nullable=False, default=0,
                               comment="Total PAYG tokens consumed this month")
    prompt_tokens     = Column(BigInteger, nullable=False, default=0,
                               comment="Total input/prompt tokens")
    completion_tokens = Column(BigInteger, nullable=False, default=0,
                               comment="Total output/completion tokens")
    input_cost        = Column(
        Numeric(precision=20, scale=8),
        nullable=False,
        default=Decimal("0.0"),
        comment="Total USD cost for input tokens",
    )
    output_cost       = Column(
        Numeric(precision=20, scale=8),
        nullable=False,
        default=Decimal("0.0"),
        comment="Total USD cost for output tokens",
    )
    total_cost        = Column(
        Numeric(precision=20, scale=8),
        nullable=False,
        default=Decimal("0.0"),
        comment="Total USD cost for PAYG tokens this month",
    )
    line_items        = Column(Text, nullable=True, comment="JSON snapshot of per-model usage, pricing rates, tokens, and costs")
    recipient_email   = Column(String, nullable=True, comment="Billing recipient email invoice was dispatched to")
    invoice_status    = Column(
        String,
        nullable=False,
        default=InvoiceStatus.PENDING.value,
        index=True,
        comment="One of: PENDING, PAID, OVERDUE, WAIVED",
    )
    generated_at      = Column(DateTime, nullable=False, default=datetime.utcnow)
    paid_at           = Column(DateTime, nullable=True, comment="Timestamp when invoice was marked paid")

    @property
    def status_enum(self) -> InvoiceStatus:
        return InvoiceStatus(self.invoice_status)

    def __repr__(self) -> str:
        return (
            f"<PAYGInvoice org={self.organization_name!r} "
            f"month={self.billing_month!r} "
            f"tokens={self.total_tokens} cost={self.total_cost} "
            f"status={self.invoice_status!r}>"
        )

logger = logging.getLogger(__name__)

@dataclass
class FilePlan:
    path: str
    approach: str
    imports_needed: List[str]
    exports_expected: List[str]
    order: int

@dataclass
class ReActPlan:
    files_to_create: List[FilePlan]
    approach_summary: str
    potential_issues: List[str]
    checklist: List[Dict[str, Any]] = field(default_factory=list)

@dataclass
class Observation:
    success: bool
    file_path: str
    errors: List[str]
    warnings: List[str]
    workspace_snapshot: List[str]

@dataclass
class FileResult:
    file_path: str
    success: bool
    content_length: int
    retries: int
    error: Optional[str]

@dataclass
class ReActResult:
    success: bool
    files_generated: int
    file_results: List[FileResult]
    total_reason_steps: int
    total_act_steps: int
    errors: List[str]
    checklist: List[Dict[str, Any]] = field(default_factory=list)

def build_task_assignment_payload(
    task: Dict[str, Any],
    agent_id: str,
    agent_persona: str = "general_builder",
    brd_text: str = "",
    agent_analysis: str = "",
) -> Dict[str, Any]:
    """
    Build a lightweight, structured JSON assignment payload for the agent.
    Gives the agent a menu of context options with clear descriptions so it can request
    only what it needs for its Reasoning/Planning step.
    """
    return {
        "task": {
            "task_id": str(task.get("task_id") or task.get("id") or "TASK-01"),
            "title": task.get("title") or task.get("taskName") or "Untitled Task",
            "task_type": task.get("task_type") or "TASK",
            "description": task.get("description") or "",
            "sprint": task.get("sprint") or "Sprint 1",
            "milestone": task.get("milestone") or "Milestone 1",
        },
        "agent_persona": agent_persona,
        "available_context_options": {
            "MASTER_BLUEPRINT": {
                "name": "Master Agent Technical Blueprint",
                "description": "Contains file registry, API contracts, data models, and architecture guidelines generated by Master Tech Lead."
            },
            "AGENT_ANALYSIS": {
                "name": "Intelligent Task Analysis",
                "description": "Targeted architectural analysis, file ownership, and dependencies for this specific task."
            },
            "SOURCE_BRD": {
                "name": "Uploaded Business Requirements Document",
                "description": "Original raw requirements uploaded by the end user."
            },
            "PEER_EXPORTS": {
                "name": "Exported Peer Symbols",
                "description": "Exported symbols, classes, and helper functions from dependent files created by peer agents."
            }
        },
        "instructions": (
            "FIRST: Reason & Plan your implementation. Analyze the task and specify which context options "
            "you require for your plan. THEN: Act & Code according to your specific persona."
        )
    }


class ReActAgentExecutor:
    def __init__(
        self,
        container_name: str,
        project_root: str,
        project_token: str,
        agent_id: str,
        tech_stack: Dict,
        agent_persona: str = "developer",
    ):
        self.container_name = container_name
        self.project_root = project_root
        self.project_token = project_token
        self.agent_id = agent_id
        self.tech_stack = tech_stack
        self.agent_persona = agent_persona
        self.max_retries_per_file = 2
        self.max_reason_iterations = 3
        self.max_context_exploration_turns = 5  # Max 5 context/file read requests before forced build
        self.max_history_chars_threshold = 50000  # Threshold to compress and reset chat window (50k)
        self.conversation_history: List[Dict[str, str]] = []

    async def execute_task(
        self,
        task: Dict,
        blueprint_slice: Dict,
        peer_exports: Dict,
        workspace_tree: str,
        brd_text: str = "",
        agent_analysis: str = "",
    ) -> ReActResult:
        """
        Main ReAct loop:
        1. REASON: produce file plan based on JSON payload + requested context options.
           (Allows up to 3 context exploration turns before forcing transition to code generation)
        2. For each file in plan:
           a. ACT: generate code based on agent persona
           b. OBSERVE: verify syntax/build
           c. If fail: REASON again with error, retry ACT
        3. Run build verification
        4. Return result
        """
        logger.info(f"Starting ReAct execution for task: {task.get('title', 'Unknown')} (Persona: {self.agent_persona})")
        
        total_reason_steps = 0
        total_act_steps = 0
        file_results: List[FileResult] = []
        global_errors: List[str] = []
        observations: List[Observation] = []
        
        # Reset chat history for this task and initialize system persona
        self.conversation_history = [
            {
                "role": "system",
                "content": f"You are an autonomous AI Agent operating under the persona of '{self.agent_persona}'. "
                           f"You build clean, modular, production-ready code matching the tech stack: {json.dumps(self.tech_stack)}"
            }
        ]
        
        # Build lightweight JSON assignment payload with context options menu
        assignment_payload = build_task_assignment_payload(
            task=task,
            agent_id=self.agent_id,
            agent_persona=self.agent_persona,
            brd_text=brd_text,
            agent_analysis=agent_analysis
        )
        
        # 1. REASON Step (Allows up to 3 context exploration turns)
        exploration_turn = 0
        plan = None
        
        while exploration_turn < self.max_context_exploration_turns and plan is None:
            exploration_turn += 1
            logger.info(f"Reason & Context Exploration Turn {exploration_turn}/{self.max_context_exploration_turns} for {task.get('title')}")
            
            # Check if chat history exceeds token/char limit, and compress if huge
            await self._check_and_compress_chat_history(task_title=task.get("title", "Task"))
            
            try:
                plan = await self._reason_step(
                    task=task,
                    assignment_payload=assignment_payload,
                    blueprint_slice=blueprint_slice,
                    peer_exports=peer_exports,
                    workspace_tree=workspace_tree,
                    brd_text=brd_text,
                    agent_analysis=agent_analysis,
                    previous_observations=observations,
                    turn_number=exploration_turn
                )
                total_reason_steps += 1
            except Exception as e:
                logger.error(f"Failed in reason step turn {exploration_turn}: {e}")
                if exploration_turn >= self.max_context_exploration_turns:
                    return ReActResult(
                        success=False,
                        files_generated=0,
                        file_results=[],
                        total_reason_steps=total_reason_steps,
                        total_act_steps=total_act_steps,
                        errors=[f"Reason step failed after {exploration_turn} turns: {str(e)}"]
                    )
        
        if not plan or not plan.files_to_create:
            logger.warning("No files planned for creation; producing fallback file plan.")
            plan = ReActPlan(
                files_to_create=[
                    FilePlan(
                        path=f"src/{task.get('title', 'task').lower().replace(' ', '_')}.py",
                        approach="Default single-file implementation",
                        imports_needed=[],
                        exports_expected=[],
                        order=1
                    )
                ],
                checklist=[
                    {"step": 1, "task_name": f"Implement {task.get('title', 'task')}", "completed": False}
                ],
                approach_summary="Fallback plan generated due to empty reasoning output.",
                potential_issues=[]
            )

        # Ensure checklist exists
        if not plan.checklist:
            plan.checklist = [
                {"step": idx, "task_name": f"Create and verify {f.path}", "completed": False}
                for idx, f in enumerate(plan.files_to_create, 1)
            ]

        # Sort files by order dependency
        sorted_files = sorted(plan.files_to_create, key=lambda f: f.order)
        
        # 2. ACT & OBSERVE for each file (with dynamic checklist tracking)
        for idx, file_plan in enumerate(sorted_files, 1):
            file_path = file_plan.path
            retries = 0
            success = False
            last_error = None
            content_length = 0
            
            while retries <= self.max_retries_per_file and not success:
                logger.info(f"ACT step for {file_path} (Attempt {retries + 1}, Persona: {self.agent_persona})")
                
                # Check chat history size before each Act step
                await self._check_and_compress_chat_history(task_title=task.get("title", "Task"))
                
                try:
                    # ACT
                    code_content = await self._act_step(
                        file_plan, task, blueprint_slice, peer_exports, 
                        workspace_tree, last_error
                    )
                    total_act_steps += 1
                    content_length = len(code_content)
                    
                    # OBSERVE
                    observation = await self._observe_step(file_path, code_content)
                    observations.append(observation)
                    workspace_tree = "\n".join(observation.workspace_snapshot)
                    
                    if observation.success:
                        success = True
                    else:
                        last_error = "; ".join(observation.errors)
                        retries += 1
                        
                except Exception as e:
                    logger.error(f"Error during act/observe for {file_path}: {e}")
                    last_error = str(e)
                    retries += 1
            
            # Update checklist status for this step
            if idx <= len(plan.checklist):
                plan.checklist[idx - 1]["completed"] = success
            else:
                for chk in plan.checklist:
                    if file_path in str(chk.get("task_name", "")):
                        chk["completed"] = success

            file_results.append(FileResult(
                file_path=file_path,
                success=success,
                content_length=content_length,
                retries=retries,
                error=last_error if not success else None
            ))
            
            if not success:
                global_errors.append(f"Failed to generate valid code for {file_path} after {retries} retries. Last error: {last_error}")

        is_fully_successful = len(global_errors) == 0 and all(r.success for r in file_results)

        return ReActResult(
            success=is_fully_successful,
            files_generated=sum(1 for r in file_results if r.success),
            file_results=file_results,
            total_reason_steps=total_reason_steps,
            total_act_steps=total_act_steps,
            errors=global_errors,
            checklist=plan.checklist
        )

    def _summarize_context_block(self, text: str, max_chars: int = 800) -> str:
        """Summarize/truncate long context blocks to keep context lightweight and fast."""
        if not text:
            return ""
        if len(text) <= max_chars:
            return text
        return text[:max_chars] + f"\n... [Summarized {len(text) - max_chars} characters for speed & context efficiency]"

    async def _check_and_compress_chat_history(self, task_title: str):
        """
        Monitors total chat history character length. If it exceeds threshold (~12k chars / 3k tokens),
        summarizes prior decisions into a State Summary and resets to a clean new chat session.
        """
        total_chars = sum(len(msg.get("content", "")) for msg in self.conversation_history)
        if total_chars < self.max_history_chars_threshold:
            return

        logger.info(f"Conversation history size ({total_chars} chars) exceeded threshold ({self.max_history_chars_threshold} chars). Summarizing and starting new chat session...")
        
        # Ask LLM for a 2-line summary of key decisions made so far
        summary_prompt = "Summarize the key architectural decisions, completed files, and active plan from this conversation history in 3 bullet points."
        temp_messages = self.conversation_history + [{"role": "user", "content": summary_prompt}]
        
        try:
            summary_text = await llm_gateway.call_llm_and_extract(messages=temp_messages, max_tokens=300)
        except Exception as err:
            logger.warning(f"Failed to generate history summary: {err}")
            summary_text = f"Working on task '{task_title}' under persona '{self.agent_persona}'."

        # Reset conversation history with compressed State Summary
        self.conversation_history = [
            {
                "role": "system",
                "content": f"You are an autonomous AI Agent with persona '{self.agent_persona}'. "
                           f"Tech Stack: {json.dumps(self.tech_stack)}"
            },
            {
                "role": "assistant",
                "content": f"--- CONTEXT COMPRESSION STATE SUMMARY ---\n{summary_text}\n--- END SUMMARY ---"
            }
        ]
        logger.info(f"Chat history compressed & new exploration session started for persona '{self.agent_persona}'")

    async def _reason_step(
        self,
        task: Dict,
        assignment_payload: Dict,
        blueprint_slice: Dict,
        peer_exports: Dict,
        workspace_tree: str,
        brd_text: str,
        agent_analysis: str,
        previous_observations: List[Observation],
        turn_number: int = 1,
    ) -> ReActPlan:
        obs_text = "None"
        if previous_observations:
            obs_text = json.dumps([
                {"file": o.file_path, "success": o.success, "errors": o.errors} 
                for o in previous_observations
            ], indent=2)

        # Context-On-Demand with Summarization Engine
        context_blocks = []
        if blueprint_slice:
            context_blocks.append(f"--- MASTER_BLUEPRINT ---\n{self._summarize_context_block(json.dumps(blueprint_slice, indent=2))}")
        if peer_exports:
            context_blocks.append(f"--- PEER_EXPORTS ---\n{self._summarize_context_block(json.dumps(peer_exports, indent=2))}")
        if agent_analysis:
            context_blocks.append(f"--- AGENT_ANALYSIS ---\n{self._summarize_context_block(agent_analysis)}")
        if brd_text:
            context_blocks.append(f"--- SOURCE_BRD ---\n{self._summarize_context_block(brd_text)}")

        injected_context = "\n\n".join(context_blocks) if context_blocks else "No additional context requested."

        user_prompt = f"""Reason & Plan Turn {turn_number}/{self.max_context_exploration_turns}:
Persona: {self.agent_persona}

TASK ASSIGNMENT PAYLOAD (JSON):
{json.dumps(assignment_payload, indent=2)}

SUMMARIZED CONTEXT:
{injected_context}

CONTAINER WORKSPACE TREE:
{workspace_tree}

PREVIOUS OBSERVATIONS:
{obs_text}

OUTPUT JSON EXACTLY IN THIS FORMAT:
{{
  "requested_context_options": ["MASTER_BLUEPRINT", "PEER_EXPORTS"],
  "files_to_create": [
    {{
      "path": "path/to/file",
      "approach": "Brief implementation approach for persona '{self.agent_persona}'",
      "imports_needed": ["list of imports"],
      "exports_expected": ["list of exports"],
      "order": 1
    }}
  ],
  "checklist": [
    {{
      "step": 1,
      "task_name": "Create and verify path/to/file",
      "completed": false
    }}
  ],
  "approach_summary": "Overall architecture plan",
  "potential_issues": ["Any potential blockers"]
}}"""

        # Append to conversational history
        self.conversation_history.append({"role": "user", "content": user_prompt})
        
        response = await llm_gateway.call_llm_and_extract(messages=self.conversation_history, max_tokens=2000)
        self.conversation_history.append({"role": "assistant", "content": response})
        
        clean_json = self._extract_code_block(response, "json")
        try:
            data = json.loads(clean_json)
            files = [FilePlan(**f) for f in data.get("files_to_create", [])]
            raw_checklist = data.get("checklist", [])
            checklist = []
            if raw_checklist and isinstance(raw_checklist, list):
                for idx, item in enumerate(raw_checklist, 1):
                    if isinstance(item, dict):
                        checklist.append({
                            "step": item.get("step", idx),
                            "task_name": item.get("task_name") or item.get("title") or item.get("text") or f"Step {idx}",
                            "completed": bool(item.get("completed", False))
                        })
                    elif isinstance(item, str):
                        checklist.append({"step": idx, "task_name": item, "completed": False})
            
            if not checklist:
                for idx, f in enumerate(files, 1):
                    checklist.append({"step": idx, "task_name": f"Create and verify {f.path}", "completed": False})

            return ReActPlan(
                files_to_create=files,
                checklist=checklist,
                approach_summary=data.get("approach_summary", ""),
                potential_issues=data.get("potential_issues", [])
            )
        except json.JSONDecodeError as e:
            logger.error(f"Failed to parse reason step JSON: {clean_json}")
            raise ValueError(f"Invalid JSON from LLM: {e}")

    async def _act_step(
        self,
        file_plan: FilePlan,
        task: Dict,
        blueprint_slice: Dict,
        peer_exports: Dict,
        workspace_tree: str,
        previous_error: Optional[str],
    ) -> str:
        blueprint_info = blueprint_slice.get(file_plan.path, {})
        purpose = blueprint_info.get("purpose", "No purpose provided")
        
        error_context = ""
        if previous_error:
            error_context = f"\nPREVIOUS ATTEMPT FAILED:\n{previous_error}\nFix these issues in your new code.\n"

        prompt = f"""You are acting under persona: {self.agent_persona}.
Generate the complete, production-ready code for this file.

File: {file_plan.path}
Purpose: {purpose}
Approach: {file_plan.approach}

Available imports from peers:
{json.dumps(peer_exports, indent=2)}

Expected exports:
{json.dumps(file_plan.exports_expected, indent=2)}

Tech Stack:
{json.dumps(self.tech_stack, indent=2)}
{error_context}
Output ONLY the raw file content. No markdown fences, no explanations. It must be valid code."""

        messages = [{"role": "user", "content": prompt}]
        response = await llm_gateway.call_llm_and_extract(messages=messages, max_tokens=4000)
        
        return self._extract_code_block(response)

    async def _observe_step(
        self,
        file_path: str,
        content: str,
    ) -> Observation:
        errors = []
        warnings = []
        
        # Check size constraints
        if len(content) < 50:
            warnings.append(f"File {file_path} is suspiciously small ({len(content)} bytes).")
        if len(content) > 50000:
            warnings.append(f"File {file_path} is suspiciously large ({len(content)} bytes).")

        # Write file to container
        write_success = await self._write_file_to_container(file_path, content)
        if not write_success:
            return Observation(
                success=False,
                file_path=file_path,
                errors=[f"Failed to write file {file_path} to container"],
                warnings=warnings,
                workspace_snapshot=await self._get_workspace_tree_list()
            )

        # Run AI-Driven Lightweight Syntax Check
        check_cmd = await self._get_ai_syntax_check_command(file_path)
        logger.info(f"Executing lightweight syntax check for {file_path}: {check_cmd}")
        
        if check_cmd:
            rc, stdout, stderr = await self._run_in_container(check_cmd)
            if rc != 0:
                # Syntax error found! Return error to agent so the agent fixes it.
                errors.append(f"Syntax check failed using command '{check_cmd}':\nSTDERR: {stderr.strip()}\nSTDOUT: {stdout.strip()}".strip())
        else:
            # Generic fallback: verify file exists and is non-empty
            rc, stdout, stderr = await self._run_in_container(f"test -s {file_path}")
            if rc != 0:
                errors.append("File is empty or does not exist after writing.")

        workspace_snapshot = await self._get_workspace_tree_list()
        
        return Observation(
            success=len(errors) == 0,
            file_path=file_path,
            errors=errors,
            warnings=warnings,
            workspace_snapshot=workspace_snapshot
        )

    async def _get_ai_syntax_check_command(self, file_path: str) -> str:
        """
        AI-driven lightweight syntax check command generator:
        Leverages AI knowledge to generate the exact lightweight syntax check command 
        for ANY file type (Python, TypeScript, JavaScript, Java, Go, Rust, Vue, Svelte, PHP, Ruby, etc.).
        Fast local fallbacks used for standard extensions.
        """
        ext = os.path.splitext(file_path)[1].lower()
        
        # Fast local fallbacks
        if ext == ".py":
            return f"python3 -m py_compile {file_path}"
        elif ext in [".js", ".jsx"]:
            return f"node --check {file_path}"
        elif ext in [".ts", ".tsx", ".vue", ".svelte"]:
            return f"npx tsc --noEmit {file_path} || node --check {file_path}"
        elif ext == ".go":
            return f"go vet {file_path}"
        elif ext == ".java":
            return f"javac -fsyntax-only {file_path} 2>/dev/null || javac {file_path}"
        elif ext == ".php":
            return f"php -l {file_path}"
        elif ext == ".rb":
            return f"ruby -c {file_path}"
        elif ext == ".rs":
            return f"cargo check 2>/dev/null || rustc --check {file_path}"
            
        # For any other custom extension or language, ask AI dynamically!
        prompt = (
            f"Generate ONLY the raw single-line shell command to check the syntax of file '{file_path}'. "
            f"Tech stack: {json.dumps(self.tech_stack)}. "
            f"Output ONLY the command string (e.g., 'python3 -m py_compile {file_path}' or 'node --check {file_path}'). "
            f"No markdown fences, no explanations."
        )
        try:
            response = await llm_gateway.call_llm_and_extract(
                messages=[{"role": "user", "content": prompt}],
                max_tokens=60
            )
            clean_cmd = self._extract_code_block(response).strip()
            return clean_cmd if clean_cmd else f"test -s {file_path}"
        except Exception as e:
            logger.warning(f"AI syntax command generation failed for {file_path}: {e}")
            return f"test -s {file_path}"



    def _detect_language(self, file_path: str) -> str:
        ext = os.path.splitext(file_path)[1].lower()
        lang_map = {
            ".py": "python",
            ".js": "javascript",
            ".jsx": "javascript",
            ".ts": "typescript",
            ".tsx": "typescript",
            ".java": "java",
            ".go": "go",
            ".rs": "rust",
            ".rb": "ruby",
            ".php": "php",
            ".cs": "csharp",
            ".kt": "kotlin",
            ".vue": "vue",
            ".svelte": "svelte",
            ".c": "c",
            ".cpp": "cpp",
            ".h": "c",
            ".hpp": "cpp",
        }
        return lang_map.get(ext, "unknown")

    def _get_syntax_check_command(self, lang: str, file_path: str) -> Optional[str]:
        if lang == "python":
            return f"python3 -m py_compile {file_path}"
        elif lang in ["typescript", "vue", "svelte"]:
            return f"npx tsc --noEmit {file_path} || node --check {file_path}"
        elif lang == "javascript":
            return f"node --check {file_path}"
        elif lang == "java":
            return f"javac {file_path}"
        elif lang == "go":
            return f"go vet {file_path}"
        elif lang == "rust":
            return f"cargo check || rustc --check {file_path}"
        elif lang == "php":
            return f"php -l {file_path}"
        elif lang == "ruby":
            return f"ruby -c {file_path}"
        return None

    async def _write_file_to_container(self, file_path: str, content: str) -> bool:
        full_container_path = os.path.join(self.project_root, file_path).replace("\\", "/")
        container_dir = os.path.dirname(full_container_path)
        
        # Ensure directory exists
        rc, _, _ = await self._run_in_container(f"mkdir -p {container_dir}")
        if rc != 0:
            return False
            
        docker_bin = shutil.which("docker") or "docker"
        fd, temp_path = tempfile.mkstemp()
        try:
            with os.fdopen(fd, 'w', encoding='utf-8') as f:
                f.write(content)
            
            # docker cp via subprocess.run
            def _cp():
                return subprocess.run(
                    [docker_bin, "cp", temp_path, f"{self.container_name}:{full_container_path}"],
                    stdout=subprocess.PIPE,
                    stderr=subprocess.PIPE,
                    text=True,
                    encoding="utf-8",
                    errors="replace"
                )
            res = await asyncio.to_thread(_cp)
            if res.returncode != 0:
                logger.error(f"Failed to copy file to container: {res.stderr}")
                return False
                
            return True
        except Exception as e:
            logger.error(f"Error writing file to container: {e}")
            return False
        finally:
            if os.path.exists(temp_path):
                os.unlink(temp_path)

    async def _get_workspace_tree_list(self) -> List[str]:
        tree = await self._get_workspace_tree()
        return tree.strip().split("\n") if tree else []

    async def _get_workspace_tree(self) -> str:
        rc, stdout, stderr = await self._run_in_container(f"find {self.project_root} -type f")
        if rc == 0:
            return stdout
        return ""

    async def _run_in_container(self, command: str, timeout: int = 30) -> Tuple[int, str, str]:
        if not self.container_name:
            logger.warning("No container_name provided to ReActAgentExecutor, skipping container command execution.")
            return (-1, "", "No container available")
        docker_bin = shutil.which("docker") or "docker"

        def _exec():
            return subprocess.run(
                [docker_bin, "exec", self.container_name, "sh", "-c", command],
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                text=True,
                encoding="utf-8",
                errors="replace",
                timeout=timeout,
            )

        try:
            res = await asyncio.to_thread(_exec)
            return (
                res.returncode if res.returncode is not None else -1,
                res.stdout or "",
                res.stderr or ""
            )
        except subprocess.TimeoutExpired:
            logger.warning(f"Command timed out after {timeout}s in container '{self.container_name}': {command}")
            return (-1, "", "Timeout expired")
        except Exception as e:
            err_msg = str(e).strip() if str(e).strip() else repr(e)
            logger.error(f"Error executing command in container '{self.container_name}': {err_msg}")
            return (-1, "", err_msg)

    def _extract_code_block(self, text: str, lang: str = "") -> str:
        """Helper to extract code/json from markdown fences if present."""
        text = text.strip()
        pattern = re.compile(r"^```" + lang + r"?\n(.*?)\n```$", re.DOTALL | re.MULTILINE)
        match = pattern.search(text)
        if match:
            return match.group(1).strip()
        # Fallback if no specific language tag but has fences
        pattern_fallback = re.compile(r"^```(?:.*)?\n(.*?)\n```$", re.DOTALL | re.MULTILINE)
        match_fallback = pattern_fallback.search(text)
        if match_fallback:
            return match_fallback.group(1).strip()
        return text
